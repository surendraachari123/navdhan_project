-- =====================================================================
-- ETL_JOBS: tracks each /run-etl invocation so a long-running pipeline
-- can be triggered by an admin and then polled for status, instead of
-- the admin's browser/client blocking on the request until it finishes.
-- =====================================================================

CREATE TABLE etl_jobs (
    job_id          VARCHAR2(36) PRIMARY KEY,   -- UUID, generated by the API
    triggered_by    VARCHAR2(50) NOT NULL,      -- username from the JWT
    status          VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL,  -- RUNNING / SUCCESS / FAILED
    output          VARCHAR2(4000),             -- captured stdout from the pipeline
    error_message   VARCHAR2(4000),
    started_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    finished_at     TIMESTAMP,
    CONSTRAINT ck_etl_jobs_status CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED'))
);

COMMIT;
